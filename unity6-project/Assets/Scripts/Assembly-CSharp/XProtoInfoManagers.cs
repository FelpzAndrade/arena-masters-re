	[Token(Token = "0x60035BA")]
	[Address(RVA = "0x1C93744", Offset = "0x1C93744", VA = "0x1C93744")]
	public static string GetFilePath(ProtoInfoTypes type)
	{
		switch (type)
		{
			case ProtoInfoTypes.Character:
				return "XML/character_xml";
			case ProtoInfoTypes.GameConst:
				return "XML/const_xml";
			case ProtoInfoTypes.Balance:
				return "XML/balance_xml";
			case ProtoInfoTypes.Item:
				return "XML/item_xml";
			case ProtoInfoTypes.LotteryBox:
				return "XML/lottery_box_xml";
			case ProtoInfoTypes.BalanceNPC:
				return "XML/npc_balance_xml";
			case ProtoInfoTypes.Stage:
				return "XML/stage_xml";
			case ProtoInfoTypes.ItemBalance:
				return "XML/item_balance_xml";
			case ProtoInfoTypes.Quest:
				return "XML/quest_xml";
			case ProtoInfoTypes.GameModeInstance:
				return "XML/gamemode_instance_xml";
			case ProtoInfoTypes.Skin:
				return "XML/skin_xml";
			case ProtoInfoTypes.TrophyReward:
				return "XML/trophyreward_xml";
			case ProtoInfoTypes.LobbyButton:
				return "XML/lobby_button_xml";
			case ProtoInfoTypes.GameMode:
				return "XML/gamemode_xml";
			case ProtoInfoTypes.IronsMission:
				return "XML/quest_irons_xml";
			case ProtoInfoTypes.Sound:
				return XProtoInfoManager_Sound.ClientFilePath;
			case ProtoInfoTypes.Colt:
				return "XML/colt_xml";
			case ProtoInfoTypes.Relic:
				return "XML/relic_xml";
			case ProtoInfoTypes.Title:
				return "XML/title_xml";
			case ProtoInfoTypes.CharacterSound:
				return "XML/character_sound_xml";
			case ProtoInfoTypes.CharAnim:
				return "XML/character_anim_xml";
			case ProtoInfoTypes.DownloadImg:
				return "XML/download_img_xml";
			case ProtoInfoTypes.Country:
				return "XML/country_xml";
			case ProtoInfoTypes.CharacterFreeRotation:
				return "XML/free_rotation_xml";
			default:
				// literal do prefixo nao resolvido no pseudo-C
				CSLog.Error("GetFilePath : unknown type " + type.ToString());
				return string.Empty;
		}
	}

	[Token(Token = "0x60035BB")]
	[Address(RVA = "0x1C93D68", Offset = "0x1C93D68", VA = "0x1C93D68", Slot = "5")]
	public override bool LoadFromLocalFile(string GameDataDirectory)
	{
		// GameDataDirectory nao e usado: tabelas do cliente vem de Resources
		foreach (KeyValuePair<ProtoInfoTypes, CSProtoInfoManagerBase> pair in m_container)
		{
			if (pair.Value == null || pair.Value.IsFrom(ProtoInfoFrom.Server))
			{
				continue;
			}
			if (!pair.Value.LoadFromLocalFile(new XFileLoader_UnityResource(GetFilePath(pair.Key))))
			{
				return false;
			}
		}
		return true;
	}

